-- =============================================================================
-- website-services | Flyway V8 | site.template_id + site_appearance
-- 前置：V7 site_template 已存在；不改 V1–V7；外观真相源不落 site 列
-- =============================================================================

-- ---------------------------------------------------------------------------
-- §1 site.template_id：选用模板（nullable；历史 Core-only 站点可空）
-- ---------------------------------------------------------------------------
ALTER TABLE site
    ADD COLUMN template_id BIGINT NULL;

COMMENT ON COLUMN site.template_id IS '选用的平台模板 site_template.id；可空；外观真相源在 site_appearance';

ALTER TABLE site
    ADD CONSTRAINT fk_site_template
        FOREIGN KEY (template_id) REFERENCES site_template (id) ON DELETE RESTRICT;

CREATE INDEX idx_site_template_id_active
    ON site (template_id) WHERE deleted = FALSE AND template_id IS NOT NULL;

-- ---------------------------------------------------------------------------
-- §2 site_appearance：站点外观（1:1；schema_version + 闭集 JSONB）
-- ---------------------------------------------------------------------------
CREATE TABLE site_appearance (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    site_id             BIGINT NOT NULL,
    schema_version      INTEGER NOT NULL,
    config              JSONB NOT NULL,
    created_at          TIMESTAMPTZ NOT NULL DEFAULT now(),
    created_by          BIGINT,
    updated_at          TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_by          BIGINT,
    deleted             BOOLEAN NOT NULL DEFAULT FALSE,
    deleted_at          TIMESTAMPTZ,
    version             INTEGER NOT NULL DEFAULT 0,
    CONSTRAINT fk_site_appearance_site
        FOREIGN KEY (site_id) REFERENCES site (id) ON DELETE RESTRICT,
    CONSTRAINT uq_site_appearance_site_id UNIQUE (site_id)
);

COMMENT ON TABLE site_appearance IS '站点外观配置真相源；与 site 1:1；config 为 schema_version 对应闭集 JSON';
COMMENT ON COLUMN site_appearance.schema_version IS '配置 schema 版本；本版读写仅接受 1';
COMMENT ON COLUMN site_appearance.config IS '外观 JSON；v1 键：primaryColor/fontStyle/buttonStyle/heroLayout';

CREATE TRIGGER tr_site_appearance_touch_updated_at
    BEFORE UPDATE ON site_appearance
    FOR EACH ROW EXECUTE PROCEDURE fn_touch_updated_at();

CREATE INDEX idx_site_appearance_site_id_active
    ON site_appearance (site_id) WHERE deleted = FALSE;
