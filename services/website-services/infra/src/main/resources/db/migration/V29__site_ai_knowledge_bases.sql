-- 知识库（base）与跨站共享：文档归属一个 base；base 可链接给其他站点，
-- 链接站点的派生索引分区会同步该 base 的文档（Java 同步层扇出，Python 无感）。
CREATE TABLE site_ai_knowledge_base (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    site_id    BIGINT      NOT NULL,
    name       VARCHAR(128) NOT NULL,
    is_default BOOLEAN     NOT NULL DEFAULT FALSE,
    status     VARCHAR(16) NOT NULL DEFAULT 'ACTIVE',
    version    INT         NOT NULL DEFAULT 0,
    deleted    BOOLEAN     NOT NULL DEFAULT FALSE,
    created_by BIGINT      NOT NULL DEFAULT 0,
    updated_by BIGINT      NOT NULL DEFAULT 0,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX idx_kb_base_site ON site_ai_knowledge_base (site_id, deleted);

COMMENT ON TABLE site_ai_knowledge_base IS '站点知识库（容器）：文档归属其一，site_id 为所有者站点';
COMMENT ON COLUMN site_ai_knowledge_base.is_default IS '是否为站点默认库（手工建档未指定时落入）';

-- 链接为纯关系行：删除即真删，不做软删（无内容价值，避免唯一约束与软删纠缠）。
CREATE TABLE site_ai_knowledge_base_link (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    base_id    BIGINT NOT NULL,
    site_id    BIGINT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_kb_base_link UNIQUE (base_id, site_id)
);

COMMENT ON TABLE site_ai_knowledge_base_link IS '知识库共享链接：base 被链接到的目标站点集合';

ALTER TABLE site_ai_knowledge_document
    ADD COLUMN base_id BIGINT;

CREATE INDEX idx_kb_document_base ON site_ai_knowledge_document (base_id, deleted);

-- 存量文档回填：每个已有文档的站点建一个默认库，文档全部归入。
INSERT INTO site_ai_knowledge_base (site_id, name, is_default, status)
SELECT DISTINCT site_id, '默认知识库', TRUE, 'ACTIVE'
FROM site_ai_knowledge_document;

UPDATE site_ai_knowledge_document d
SET base_id = (
    SELECT b.id
    FROM site_ai_knowledge_base b
    WHERE b.site_id = d.site_id AND b.is_default = TRUE AND b.deleted = FALSE
);
