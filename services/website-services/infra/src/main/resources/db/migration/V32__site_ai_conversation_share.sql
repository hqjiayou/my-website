-- 对话分享链接（GPT 式快照分享）：每个会话至多一条有效分享，token 随机不可猜；
-- snapshot 为分享时刻的会话快照 JSON（标题＋消息正文＋附件计数/文件名，不含图片数据）。
-- 会话硬删时分享随之失效（ON DELETE CASCADE），与「删会话即撤分享」的产品语义一致。
CREATE TABLE site_ai_conversation_share (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    conversation_id BIGINT NOT NULL,
    site_id         BIGINT NOT NULL,
    site_user_id    BIGINT NOT NULL,
    token           VARCHAR(64) NOT NULL,
    snapshot        JSONB NOT NULL,
    created_at      TIMESTAMPTZ NOT NULL DEFAULT now(),
    created_by      BIGINT,
    updated_at      TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_by      BIGINT,
    deleted         BOOLEAN NOT NULL DEFAULT FALSE,
    deleted_at      TIMESTAMPTZ,
    version         INTEGER NOT NULL DEFAULT 0,
    CONSTRAINT uq_site_ai_conversation_share_token UNIQUE (token),
    CONSTRAINT uq_site_ai_conversation_share_conversation UNIQUE (conversation_id),
    CONSTRAINT fk_site_ai_conversation_share_conversation
        FOREIGN KEY (conversation_id) REFERENCES site_ai_conversation (id) ON DELETE CASCADE,
    CONSTRAINT fk_site_ai_conversation_share_site
        FOREIGN KEY (site_id) REFERENCES site (id) ON DELETE RESTRICT,
    CONSTRAINT fk_site_ai_conversation_share_site_user
        FOREIGN KEY (site_user_id) REFERENCES site_user (id) ON DELETE RESTRICT
);
