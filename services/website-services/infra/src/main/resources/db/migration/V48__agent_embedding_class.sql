-- =============================================================================
-- website-services | Flyway V48 | 嵌入类登记表（Issue #126 UoW-1）
-- 登记制：嵌入类的唯一来源从「扫模型入口 embeddingSpec 推算」改为显式登记。
-- 一行＝一个已登记的嵌入类，登记行只引用模型入口（entry_id）：类的
-- embeddingSpec / key / baseUrl 运行时从被引用入口解析，登记表不存 spec、
-- 不存 key——key 轮换只改入口一处（kou 2026-11-03 拍板）。
-- agent_id 为 NULL＝全站 scope，非空＝该站点 scope；双层合并（站点优先）
-- 是 UoW-2 消费侧的事，本表只存各 scope 自己的登记行。
-- 资格（入口须 mode=KEY 且 embeddingSpec 非空）、同 scope 内规范化类键唯一、
-- 每 scope 上限 4 类，都在服务层校验（类键规范化在 Java 侧
-- AgentEmbeddingClassUtils，DB 无法表达），本表不落相关约束。
-- =============================================================================

CREATE TABLE agent_embedding_class (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    agent_id    BIGINT,
    entry_id    BIGINT NOT NULL,
    enabled     BOOLEAN NOT NULL DEFAULT TRUE,
    sort_order  INTEGER NOT NULL DEFAULT 0,
    created_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
    created_by  BIGINT,
    updated_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_by  BIGINT,
    deleted     BOOLEAN NOT NULL DEFAULT FALSE,
    deleted_at  TIMESTAMPTZ,
    version     INTEGER NOT NULL DEFAULT 0
);

COMMENT ON TABLE agent_embedding_class IS '嵌入类登记（#126）：一行一个登记类，只引用模型入口，类凭据运行时从入口解析';
COMMENT ON COLUMN agent_embedding_class.agent_id IS '所属站点 id；NULL＝全站 scope';
COMMENT ON COLUMN agent_embedding_class.entry_id IS '被引用的模型入口 id（agent_model_entry）；须 mode=KEY 且 embeddingSpec 非空';
COMMENT ON COLUMN agent_embedding_class.enabled IS '是否启用该登记类';
COMMENT ON COLUMN agent_embedding_class.sort_order IS 'scope 内顺序（整表保存时按提交数组序写入），决定类优先级';

CREATE TRIGGER tr_agent_embedding_class_touch_updated_at
    BEFORE UPDATE ON agent_embedding_class
    FOR EACH ROW EXECUTE PROCEDURE fn_touch_updated_at();

CREATE INDEX idx_agent_embedding_class_scope ON agent_embedding_class (agent_id, sort_order);
