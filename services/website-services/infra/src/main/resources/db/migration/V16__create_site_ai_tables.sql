-- 前置：V1 site / site_user
-- site_ai_prompt_profile：站点级 Prompt/AI 配置（每站至多一条 active）
-- site_ai_conversation / site_ai_message：会话与消息（Python 不持久化会话）
-- =============================================================================

CREATE TABLE site_ai_prompt_profile (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    site_id             BIGINT NOT NULL,
    system_prompt       TEXT,
    temperature         NUMERIC(3, 2),
    created_at          TIMESTAMPTZ NOT NULL DEFAULT now(),
    created_by          BIGINT,
    updated_at          TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_by          BIGINT,
    deleted             BOOLEAN NOT NULL DEFAULT FALSE,
    deleted_at          TIMESTAMPTZ,
    version             INTEGER NOT NULL DEFAULT 0,
    CONSTRAINT fk_site_ai_prompt_profile_site
        FOREIGN KEY (site_id) REFERENCES site (id) ON DELETE RESTRICT,
    CONSTRAINT ck_site_ai_prompt_profile_temperature CHECK (
        temperature IS NULL OR (temperature >= 0 AND temperature <= 2)
    )
);

COMMENT ON TABLE site_ai_prompt_profile IS '站点级 AI Prompt/参数配置；trusted internal field，永不接受前台直传';
COMMENT ON COLUMN site_ai_prompt_profile.system_prompt IS '站点 system prompt；NULL 用运行时默认';
COMMENT ON COLUMN site_ai_prompt_profile.temperature IS '0–2；NULL 用 Provider 默认';

CREATE TRIGGER tr_site_ai_prompt_profile_touch_updated_at
    BEFORE UPDATE ON site_ai_prompt_profile
    FOR EACH ROW EXECUTE PROCEDURE fn_touch_updated_at();

-- 每站至多一条 active 配置
CREATE UNIQUE INDEX uq_site_ai_prompt_profile_site_active
    ON site_ai_prompt_profile (site_id) WHERE deleted = FALSE;

CREATE TABLE site_ai_conversation (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    site_id             BIGINT NOT NULL,
    site_user_id        BIGINT NOT NULL,
    title               VARCHAR(255),
    last_message_at     TIMESTAMPTZ,
    created_at          TIMESTAMPTZ NOT NULL DEFAULT now(),
    created_by          BIGINT,
    updated_at          TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_by          BIGINT,
    deleted             BOOLEAN NOT NULL DEFAULT FALSE,
    deleted_at          TIMESTAMPTZ,
    version             INTEGER NOT NULL DEFAULT 0,
    CONSTRAINT fk_site_ai_conversation_site
        FOREIGN KEY (site_id) REFERENCES site (id) ON DELETE RESTRICT,
    CONSTRAINT fk_site_ai_conversation_site_user
        FOREIGN KEY (site_user_id) REFERENCES site_user (id) ON DELETE RESTRICT
);

COMMENT ON TABLE site_ai_conversation IS 'AI 会话；归属 site_user；Python 侧 stateless';
COMMENT ON COLUMN site_ai_conversation.title IS '会话标题（首条用户消息截断）';
COMMENT ON COLUMN site_ai_conversation.last_message_at IS '最近消息时间（列表排序用）';

CREATE TRIGGER tr_site_ai_conversation_touch_updated_at
    BEFORE UPDATE ON site_ai_conversation
    FOR EACH ROW EXECUTE PROCEDURE fn_touch_updated_at();

CREATE INDEX idx_site_ai_conversation_site_user_active
    ON site_ai_conversation (site_id, site_user_id, last_message_at DESC) WHERE deleted = FALSE;

CREATE TABLE site_ai_message (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    conversation_id     BIGINT NOT NULL,
    site_id             BIGINT NOT NULL,
    role                VARCHAR(16) NOT NULL,
    content             TEXT NOT NULL,
    created_at          TIMESTAMPTZ NOT NULL DEFAULT now(),
    created_by          BIGINT,
    updated_at          TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_by          BIGINT,
    deleted             BOOLEAN NOT NULL DEFAULT FALSE,
    deleted_at          TIMESTAMPTZ,
    version             INTEGER NOT NULL DEFAULT 0,
    CONSTRAINT fk_site_ai_message_conversation
        FOREIGN KEY (conversation_id) REFERENCES site_ai_conversation (id) ON DELETE RESTRICT,
    CONSTRAINT fk_site_ai_message_site
        FOREIGN KEY (site_id) REFERENCES site (id) ON DELETE RESTRICT,
    CONSTRAINT ck_site_ai_message_role CHECK (role IN ('USER', 'ASSISTANT'))
);

COMMENT ON TABLE site_ai_message IS 'AI 消息（append-only 业务语义）；role 闭集 USER|ASSISTANT';
COMMENT ON COLUMN site_ai_message.site_id IS '冗余站点归属，避免跨会话越权查询多一跳';

CREATE TRIGGER tr_site_ai_message_touch_updated_at
    BEFORE UPDATE ON site_ai_message
    FOR EACH ROW EXECUTE PROCEDURE fn_touch_updated_at();

CREATE INDEX idx_site_ai_message_conversation_active
    ON site_ai_message (conversation_id, id) WHERE deleted = FALSE;
