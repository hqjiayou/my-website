-- =============================================================================
-- website-services | Flyway V11 | site_content（站点区块内容）
-- 前置：V1 site；V9 media_file（cover_media_id 可选 FK）
-- 单表固定 type；非万能 CMS；封面真相源为 media_file，不存 imageUrl
-- =============================================================================

CREATE TABLE site_content (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    site_id             BIGINT NOT NULL,
    type                VARCHAR(32) NOT NULL,
    title               VARCHAR(255) NOT NULL,
    body                TEXT,
    status              VARCHAR(32) NOT NULL,
    sort_order          INTEGER NOT NULL DEFAULT 0,
    cover_media_id      BIGINT,
    published_at        TIMESTAMPTZ,
    created_at          TIMESTAMPTZ NOT NULL DEFAULT now(),
    created_by          BIGINT,
    updated_at          TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_by          BIGINT,
    deleted             BOOLEAN NOT NULL DEFAULT FALSE,
    deleted_at          TIMESTAMPTZ,
    version             INTEGER NOT NULL DEFAULT 0,
    CONSTRAINT fk_site_content_site
        FOREIGN KEY (site_id) REFERENCES site (id) ON DELETE RESTRICT,
    CONSTRAINT fk_site_content_cover_media
        FOREIGN KEY (cover_media_id) REFERENCES media_file (id) ON DELETE RESTRICT,
    CONSTRAINT ck_site_content_type CHECK (
        type IN ('hero', 'service', 'case', 'faq', 'news', 'about', 'cta')
    ),
    CONSTRAINT ck_site_content_status CHECK (
        status IN ('DRAFT', 'PUBLISHED', 'HIDDEN')
    )
);

COMMENT ON TABLE site_content IS '站点区块内容；type 闭集；封面可选关联 media_file';
COMMENT ON COLUMN site_content.type IS 'hero|service|case|faq|news|about|cta';
COMMENT ON COLUMN site_content.status IS 'DRAFT|PUBLISHED|HIDDEN';
COMMENT ON COLUMN site_content.body IS '纯文本正文；对应前端描述字段';
COMMENT ON COLUMN site_content.cover_media_id IS '可选封面媒体；须同站且 READY';
COMMENT ON COLUMN site_content.published_at IS '进入 PUBLISHED 时写入/刷新';

CREATE TRIGGER tr_site_content_touch_updated_at
    BEFORE UPDATE ON site_content
    FOR EACH ROW EXECUTE PROCEDURE fn_touch_updated_at();

CREATE INDEX idx_site_content_site_id_active
    ON site_content (site_id) WHERE deleted = FALSE;

CREATE INDEX idx_site_content_site_type_active
    ON site_content (site_id, type) WHERE deleted = FALSE;

CREATE INDEX idx_site_content_site_status_active
    ON site_content (site_id, status) WHERE deleted = FALSE;

CREATE INDEX idx_site_content_cover_media_id_active
    ON site_content (cover_media_id) WHERE deleted = FALSE AND cover_media_id IS NOT NULL;
