-- =============================================================================
-- website-services | Flyway V56 | 检索同步问题表（Issue #203）
-- Java 同步层向 Python 派生索引扇出（upsert/delete）失败时落行，不再只记日志：
--   op=DELETE：删文档/解链/非 ACTIVE 删除的 tombstone，防已删文档在 pgvector
--              里继续被检索命中（幽灵命中）；
--   op=UPSERT：链接分区扇出失败，消费站点分区滞后在管理面无信号的问题。
-- AdminAiKnowledgeServiceImpl 的定时重试任务消费本表：成功删行，失败累加
-- attempts/last_error。所有者分区 upsert 失败不入表（文档 index_status=FAILED
-- 已有信号，避免双口径）。纯问题行：解决即真删，不走软删。
-- =============================================================================

CREATE TABLE agent_ai_knowledge_retrieval_sync_issue (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    agent_id   BIGINT       NOT NULL,
    source_id  VARCHAR(64)  NOT NULL,
    op         VARCHAR(8)   NOT NULL,
    attempts   INT          NOT NULL DEFAULT 0,
    last_error VARCHAR(512),
    created_at TIMESTAMPTZ  NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ  NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_kb_retrieval_sync_issue UNIQUE (agent_id, source_id, op),
    CONSTRAINT ck_kb_retrieval_sync_issue_op CHECK (op IN ('DELETE', 'UPSERT'))
);

COMMENT ON TABLE agent_ai_knowledge_retrieval_sync_issue IS '检索派生索引同步问题（待重试）：DELETE=待删残留（tombstone）| UPSERT=链接分区待同步';
COMMENT ON COLUMN agent_ai_knowledge_retrieval_sync_issue.agent_id IS '目标分区站点 id（向量行所在的 agent 分区）';
COMMENT ON COLUMN agent_ai_knowledge_retrieval_sync_issue.source_id IS '文档来源 id，形如 kb:{documentId}';
COMMENT ON COLUMN agent_ai_knowledge_retrieval_sync_issue.attempts IS '首次落行后的重试失败次数';
