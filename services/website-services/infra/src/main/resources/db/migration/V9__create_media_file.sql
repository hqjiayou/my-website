-- =============================================================================
-- website-services | Flyway V9 | media_file（站点私有媒体元数据）
-- 前置：V1 site；对象字节在 MinIO，本表为业务真相源
-- =============================================================================

CREATE TABLE media_file (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    site_id             BIGINT NOT NULL,
    bucket              VARCHAR(128) NOT NULL,
    object_key          VARCHAR(512) NOT NULL,
    original_filename   VARCHAR(255) NOT NULL,
    content_type        VARCHAR(128) NOT NULL,
    extension           VARCHAR(16) NOT NULL,
    file_size           BIGINT NOT NULL,
    sha256              VARCHAR(64),
    visibility          VARCHAR(32) NOT NULL DEFAULT 'PRIVATE',
    status              VARCHAR(32) NOT NULL,
    created_at          TIMESTAMPTZ NOT NULL DEFAULT now(),
    created_by          BIGINT,
    updated_at          TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_by          BIGINT,
    deleted             BOOLEAN NOT NULL DEFAULT FALSE,
    deleted_at          TIMESTAMPTZ,
    version             INTEGER NOT NULL DEFAULT 0,
    CONSTRAINT fk_media_file_site
        FOREIGN KEY (site_id) REFERENCES site (id) ON DELETE RESTRICT,
    CONSTRAINT ck_media_file_file_size_nonneg CHECK (file_size >= 0)
);

COMMENT ON TABLE media_file IS '站点私有媒体元数据；对象存储路径为 sites/{siteId}/{yyyy}/{MM}/{uuid}.{ext}';
COMMENT ON COLUMN media_file.content_type IS '服务端内容检测后的 MIME，非客户端声称';
COMMENT ON COLUMN media_file.extension IS '由检测 MIME 映射的规范后缀';
COMMENT ON COLUMN media_file.visibility IS '本轮固定 PRIVATE';
COMMENT ON COLUMN media_file.status IS 'UPLOADING → READY | FAILED；删除走软删';

CREATE TRIGGER tr_media_file_touch_updated_at
    BEFORE UPDATE ON media_file
    FOR EACH ROW EXECUTE PROCEDURE fn_touch_updated_at();

CREATE UNIQUE INDEX uq_media_file_object_key ON media_file (object_key);

CREATE INDEX idx_media_file_site_id_active
    ON media_file (site_id) WHERE deleted = FALSE;

CREATE INDEX idx_media_file_status_active
    ON media_file (status) WHERE deleted = FALSE;
