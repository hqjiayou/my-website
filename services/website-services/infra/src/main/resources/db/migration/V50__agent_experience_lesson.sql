-- =============================================================================
-- website-services | Flyway V50 | 经验沉淀条目表（Issue #184 UoW-1）
-- DB 为经验条目的唯一真相源（P6 定案）：候选从正式对话提炼（UoW-2）落本表
-- 待审，人审（UoW-3）批准后经请求注入（P5 定案）在对话组装时生效（UoW-4）。
-- harness/EXPERIENCE.md 只留 L1–L5 历史存档，不再是生效通道。
-- 条目格式为结构化四字段（P4 定案）：title / symptom / lesson / evidence，
-- 其中 lesson 就是入 prompt 的规则文本，组装侧零再加工。
-- 状态机：PENDING（待审）→ APPROVED（已批准，分配 lesson_no）／REJECTED（驳回）；
-- APPROVED → DISABLED（停用，lesson_no 保留不回收，编号永不重用）。
-- lesson_no 从 6 起：L1–L5 是 EXPERIENCE.md 的历史存档编号，不入本表。
-- 未批准（lesson_no 为空）的条目不经任何通道下发。
-- =============================================================================

CREATE TABLE agent_experience_lesson (
    id                     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title                  VARCHAR(256) NOT NULL,
    symptom                TEXT,
    lesson                 TEXT NOT NULL,
    evidence               TEXT,
    source_agent_id        BIGINT,
    source_conversation_id BIGINT,
    source_message_id      BIGINT,
    status                 VARCHAR(16) NOT NULL DEFAULT 'PENDING',
    lesson_no              INTEGER,
    reviewed_at            TIMESTAMPTZ,
    created_at             TIMESTAMPTZ NOT NULL DEFAULT now(),
    created_by             BIGINT,
    updated_at             TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_by             BIGINT,
    deleted                BOOLEAN NOT NULL DEFAULT FALSE,
    deleted_at             TIMESTAMPTZ,
    version                INTEGER NOT NULL DEFAULT 0,
    CONSTRAINT ck_agent_experience_lesson_status
        CHECK (status IN ('PENDING', 'APPROVED', 'REJECTED', 'DISABLED')),
    CONSTRAINT ck_agent_experience_lesson_lesson_no
        CHECK (lesson_no IS NULL OR lesson_no >= 6)
);

COMMENT ON TABLE agent_experience_lesson IS '经验沉淀条目（#184）：一行一条候选/已批准教训，DB 为唯一真相源';
COMMENT ON COLUMN agent_experience_lesson.title IS '条目标题（简短命名，供审核列表与去重比对）';
COMMENT ON COLUMN agent_experience_lesson.symptom IS '症状：出问题时的现象与场景（提炼自失败对话）';
COMMENT ON COLUMN agent_experience_lesson.lesson IS '教训正文：入 prompt 的规则文本（批准时可被人审改写，存改写后版本）';
COMMENT ON COLUMN agent_experience_lesson.evidence IS '证据/来源说明（失败信号、对话摘录要点等）';
COMMENT ON COLUMN agent_experience_lesson.source_agent_id IS '来源对话所属 agent id；手动新建候选时为空';
COMMENT ON COLUMN agent_experience_lesson.source_conversation_id IS '来源对话 id（agent_ai_conversation）；手动新建时为空';
COMMENT ON COLUMN agent_experience_lesson.source_message_id IS '来源消息 id（agent_ai_message，含失败信号的 ASSISTANT 轮）；无具体消息时为空';
COMMENT ON COLUMN agent_experience_lesson.status IS '状态机：PENDING 待审／APPROVED 已批准／REJECTED 已驳回／DISABLED 已停用';
COMMENT ON COLUMN agent_experience_lesson.lesson_no IS 'L 编号（整数部分，展示为 L{no}）：批准时按现有最大值+1 分配、从 6 起，未批准为空，停用不回收';
COMMENT ON COLUMN agent_experience_lesson.reviewed_at IS '最近一次审核动作（批准/驳回/停用）的时间';

CREATE TRIGGER tr_agent_experience_lesson_touch_updated_at
    BEFORE UPDATE ON agent_experience_lesson
    FOR EACH ROW EXECUTE PROCEDURE fn_touch_updated_at();

-- L 编号全局唯一（未批准的 NULL 不参与，PostgreSQL 唯一索引允许多行 NULL）。
CREATE UNIQUE INDEX uq_agent_experience_lesson_lesson_no
    ON agent_experience_lesson (lesson_no)
    WHERE lesson_no IS NOT NULL;

-- 审核队列按状态＋时间扫；来源对话反查走 source_conversation_id。
CREATE INDEX idx_agent_experience_lesson_status_created
    ON agent_experience_lesson (status, created_at ASC);
CREATE INDEX idx_agent_experience_lesson_source_conversation
    ON agent_experience_lesson (source_conversation_id);
