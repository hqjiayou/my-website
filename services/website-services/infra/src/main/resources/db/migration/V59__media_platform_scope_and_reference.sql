-- =============================================================================
-- website-services | Flyway V59 | 媒体库平台化（Issue #212，解耦 Phase 4 / UoW-10）
-- media_file 归属语义由「站点私有」改平台：site_id 保留为上传来源留痕（仍 NOT NULL），
-- 新增 scope 可见范围（AGENT=仅来源站与引用站可见 / PLATFORM=平台可见，存量默认 AGENT
-- 行为不变）；跨站共享走 media_reference 引用行（引用不复制对象，对象只存一份）。
-- V33 已把 site 表改名为 agent，media_reference.agent_id 的 FK 指向 agent(id)；
-- media_file.site_id 的既有 FK 随 V33 改名已自动指向 agent(id)，本迁移不动。
-- =============================================================================

ALTER TABLE media_file
    ADD COLUMN scope VARCHAR(32) NOT NULL DEFAULT 'AGENT';

COMMENT ON TABLE media_file IS '平台媒体元数据（归属平台，site_id 为上传来源留痕）；对象存储路径为 sites/{siteId}/{yyyy}/{MM}/{uuid}.{ext}';
COMMENT ON COLUMN media_file.site_id IS '上传来源站（留痕，非归属）';
COMMENT ON COLUMN media_file.scope IS '可见范围：AGENT=仅来源站与引用站可见 | PLATFORM=平台可见';

CREATE INDEX idx_media_file_scope_active
    ON media_file (scope) WHERE deleted = FALSE;

CREATE TABLE media_reference (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    media_id   BIGINT NOT NULL,
    agent_id   BIGINT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    created_by BIGINT,
    CONSTRAINT fk_media_reference_media
        FOREIGN KEY (media_id) REFERENCES media_file (id) ON DELETE RESTRICT,
    CONSTRAINT fk_media_reference_agent
        FOREIGN KEY (agent_id) REFERENCES agent (id) ON DELETE RESTRICT,
    CONSTRAINT uk_media_reference_media_agent UNIQUE (media_id, agent_id)
);

COMMENT ON TABLE media_reference IS '媒体跨站引用（纯关系行，删除即真删）：引用站经本行获得对 PLATFORM 文件的可见权，引用不复制对象';
COMMENT ON COLUMN media_reference.media_id IS '被引用的 media_file id';
COMMENT ON COLUMN media_reference.agent_id IS '引用站 id（agent）';

CREATE INDEX idx_media_reference_agent_id ON media_reference (agent_id);
