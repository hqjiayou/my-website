-- 捆在一起，本迁移按性质拆开：
--   §1 Prompt 部分升为独立资产 agent_prompt_template（名称＋提示词文本＋温度）；
--      旧表 agent_ai_prompt_profile 是 agent 1:1 形态、无名称列，不适合升格，
--      故新建表；旧 profile 表与配置预设表都保留备查，运行时自本版起停读。
--   §2 agent 新增 Prompt 本地副本字段（prompt_system_prompt / prompt_temperature）
--      ＋来源模板留痕（prompt_template_id）＋自有技能集（default_skill_ids，
--      有序 JSON 数组文本，形态与预设原列及 V69 自有链同风格）。
--   §3 回填（等价性）：每个未删配置预设生成一条同名模板（prompt 部分逐字）；
--      引用了未删预设的未删 agent，把预设 prompt 拷为本地副本、skills 拷入
--      自有技能集、留痕指向生成的模板——迁移前后同一 agent 的有效 prompt 与
--      有效技能集不变。未引用／引用已删预设的 agent 保持全空：解析继续走
--      既有兜底（无 profile / Python env 默认集），严禁把兜底集固化进 agent 行。
--   §4 工具组新增「Prompt 模板」菜单（route /ai/prompt-templates，icon 用
--      UoW-1 已在前端 ICON_MAP 预登记的 file-text）。
-- config_preset_id 列保留停用：本迁移不写它、解析与管理面自本版起不再读写，
-- 列的删除留 UoW-7 评估。FK fk_agent_config_preset 保留不动。
