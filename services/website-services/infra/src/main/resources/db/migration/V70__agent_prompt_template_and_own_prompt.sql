-- ---------------------------------------------------------------------------
-- §1 Prompt 模板资产
-- ---------------------------------------------------------------------------
CREATE TABLE agent_prompt_template (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name                VARCHAR(255) NOT NULL,
    system_prompt       TEXT,
    temperature         NUMERIC(3, 2),
    created_at          TIMESTAMPTZ NOT NULL DEFAULT now(),
    created_by          BIGINT,
    updated_at          TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_by          BIGINT,
    deleted             BOOLEAN NOT NULL DEFAULT FALSE,
    deleted_at          TIMESTAMPTZ,
    version             INTEGER NOT NULL DEFAULT 0,
    CONSTRAINT ck_agent_prompt_template_temperature CHECK (
        temperature IS NULL OR (temperature >= 0 AND temperature <= 2)
    )
);

COMMENT ON TABLE agent_prompt_template IS 'Prompt 模板（#214 UoW-4）：命名提示词资产，agent 套用即拷贝、之后互不联动';
COMMENT ON COLUMN agent_prompt_template.name IS '模板名称（管理面展示，可改）';
COMMENT ON COLUMN agent_prompt_template.system_prompt IS 'system prompt 文本；NULL 表示模板不带提示词';
COMMENT ON COLUMN agent_prompt_template.temperature IS '0–2；NULL 用 Provider 默认';

CREATE TRIGGER tr_agent_prompt_template_touch_updated_at
    BEFORE UPDATE ON agent_prompt_template
    FOR EACH ROW EXECUTE PROCEDURE fn_touch_updated_at();

-- ---------------------------------------------------------------------------
-- §2 agent 本地副本＋留痕＋自有技能集
-- ---------------------------------------------------------------------------
ALTER TABLE agent
    ADD COLUMN prompt_system_prompt TEXT,
    ADD COLUMN prompt_temperature NUMERIC(3, 2),
    ADD COLUMN prompt_template_id BIGINT,
    ADD COLUMN default_skill_ids TEXT,
    ADD CONSTRAINT ck_agent_prompt_temperature CHECK (
        prompt_temperature IS NULL OR (prompt_temperature >= 0 AND prompt_temperature <= 2)
    ),
    ADD CONSTRAINT fk_agent_prompt_template
        FOREIGN KEY (prompt_template_id) REFERENCES agent_prompt_template (id) ON DELETE RESTRICT;

COMMENT ON COLUMN agent.prompt_system_prompt IS 'Prompt 本地副本（#214 UoW-4）；NULL 且温度/留痕皆空＝未配置，解析回退与旧无 profile 一致';
COMMENT ON COLUMN agent.prompt_temperature IS '本地副本温度 0–2；NULL 用 Provider 默认';
COMMENT ON COLUMN agent.prompt_template_id IS '来源模板留痕（套用/另存时写入）；仅记录出处，模板后续修改不影响本地副本';
COMMENT ON COLUMN agent.default_skill_ids IS '自有默认 skill 集（有序 JSON 数组文本，#214 UoW-4）；NULL/空＝无自有集，正式对话回退平台 env 默认';

-- ---------------------------------------------------------------------------
-- §3 回填：预设 → 模板（逐条生成以便拿到 id 回填留痕）；引用 agent 拷贝。
-- 审计列随源预设带过来，保持迁移前后可追溯（同 V60 平移口径）。
-- ---------------------------------------------------------------------------
DO $$
DECLARE
    r RECORD;
    new_template_id BIGINT;
BEGIN
    FOR r IN
        SELECT p.id AS preset_id,
               p.name,
               p.system_prompt,
               p.temperature,
               p.default_skill_ids,
               p.created_at,
               p.created_by,
               p.updated_at,
               p.updated_by
          FROM agent_ai_config_preset p
         WHERE p.deleted = FALSE
    LOOP
        INSERT INTO agent_prompt_template (
            name, system_prompt, temperature,
            created_at, created_by, updated_at, updated_by)
        VALUES (
            r.name, r.system_prompt, r.temperature,
            r.created_at, r.created_by, r.updated_at, r.updated_by)
        RETURNING id INTO new_template_id;

        UPDATE agent a
           SET prompt_system_prompt = r.system_prompt,
               prompt_temperature = r.temperature,
               prompt_template_id = new_template_id,
               default_skill_ids = r.default_skill_ids
         WHERE a.config_preset_id = r.preset_id
           AND a.deleted = FALSE;
    END LOOP;
END $$;

-- ---------------------------------------------------------------------------
-- §4 「Prompt 模板」菜单（工具组，排在 MCP 之后；仿 V67 §4 口径）
-- ---------------------------------------------------------------------------
INSERT INTO admin_permission (
    permission_code, permission_name, resource_type, resource_key, status,
    parent_id, sort_order, route_path, icon, deleted, version)
SELECT 'admin:menu:ai.prompttemplates', 'Prompt 模板', 'MENU', 'ai.prompttemplates', 'ACTIVE',
       (SELECT id FROM admin_permission
        WHERE permission_code = 'admin:menu:tools' AND deleted = FALSE),
       20, '/ai/prompt-templates', 'file-text', FALSE, 0
WHERE NOT EXISTS (
    SELECT 1 FROM admin_permission p
    WHERE p.permission_code = 'admin:menu:ai.prompttemplates' AND p.deleted = FALSE
);

INSERT INTO admin_role_permission (admin_role_id, admin_permission_id, deleted, version)
SELECT r.id, p.id, FALSE, 0
FROM admin_role r
CROSS JOIN admin_permission p
WHERE r.role_code = 'admin'
  AND r.deleted = FALSE
  AND p.deleted = FALSE
  AND p.status = 'ACTIVE'
  AND p.permission_code = 'admin:menu:ai.prompttemplates'
  AND NOT EXISTS (
      SELECT 1 FROM admin_role_permission rp
      WHERE rp.admin_role_id = r.id
        AND rp.admin_permission_id = p.id
        AND rp.deleted = FALSE
  );
