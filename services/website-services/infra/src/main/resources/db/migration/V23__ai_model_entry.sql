-- =============================================================================
-- website-services | Flyway V23 | 平台模型入口（Java 持有，Python 只执行）
-- 一条启用且 is_default 的记录是站点对话与后台预览使用的模型。
-- 未设默认入口时，agent-services 仍回退进程环境变量 AI_MODEL。
-- api_key 是密钥：管理接口只回末尾提示，不回正文。
-- =============================================================================

CREATE TABLE ai_model_entry (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    display_name        VARCHAR(128) NOT NULL,
    model_spec          VARCHAR(256) NOT NULL,
    api_key             TEXT NOT NULL,
    base_url            VARCHAR(512),
    enabled             BOOLEAN NOT NULL DEFAULT TRUE,
    is_default          BOOLEAN NOT NULL DEFAULT FALSE,
    created_at          TIMESTAMPTZ NOT NULL DEFAULT now(),
    created_by          BIGINT,
    updated_at          TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_by          BIGINT,
    deleted             BOOLEAN NOT NULL DEFAULT FALSE,
    deleted_at          TIMESTAMPTZ,
    version             INTEGER NOT NULL DEFAULT 0,
    CONSTRAINT ck_ai_model_entry_display_name CHECK (length(trim(display_name)) > 0),
    CONSTRAINT ck_ai_model_entry_model_spec CHECK (length(trim(model_spec)) > 0),
    CONSTRAINT ck_ai_model_entry_api_key CHECK (length(trim(api_key)) > 0)
);

COMMENT ON TABLE ai_model_entry IS '平台模型入口；api_key 不得出现在管理接口响应中';
COMMENT ON COLUMN ai_model_entry.model_spec IS 'Pydantic AI spec，如 google:gemini-3-flash-preview';
COMMENT ON COLUMN ai_model_entry.api_key IS '该入口的 Provider key；只存库，接口只回末尾提示';
COMMENT ON COLUMN ai_model_entry.is_default IS '启用中的默认入口才参与对话；同时至多一条';

CREATE TRIGGER tr_ai_model_entry_touch_updated_at
    BEFORE UPDATE ON ai_model_entry
    FOR EACH ROW EXECUTE PROCEDURE fn_touch_updated_at();

CREATE UNIQUE INDEX uq_ai_model_entry_one_default
    ON ai_model_entry (is_default) WHERE deleted = FALSE AND is_default = TRUE;

INSERT INTO admin_permission (
    permission_code, permission_name, resource_type, resource_key, status,
    parent_id, sort_order, route_path, icon, deleted, version)
SELECT v.code, v.name, 'ACTION', v.rkey, 'ACTIVE',
       NULL, 0, NULL, NULL, FALSE, 0
FROM (VALUES
    ('admin:ai-model:read', '查看模型入口', 'ai-model:read'),
    ('admin:ai-model:update', '维护模型入口', 'ai-model:update')
) AS v(code, name, rkey)
WHERE NOT EXISTS (
    SELECT 1 FROM admin_permission p
    WHERE p.permission_code = v.code AND p.deleted = FALSE
);

INSERT INTO admin_role_permission (admin_role_id, admin_permission_id, deleted, version)
SELECT r.id, p.id, FALSE, 0
FROM admin_role r
CROSS JOIN admin_permission p
WHERE r.role_code = 'admin'
  AND r.deleted = FALSE
  AND p.deleted = FALSE
  AND p.status = 'ACTIVE'
  AND p.permission_code LIKE 'admin:ai-model:%'
  AND NOT EXISTS (
      SELECT 1 FROM admin_role_permission rp
      WHERE rp.admin_role_id = r.id
        AND rp.admin_permission_id = p.id
        AND rp.deleted = FALSE
  );
