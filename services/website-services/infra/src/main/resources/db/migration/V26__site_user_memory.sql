-- =============================================================================
-- website-services | Flyway V26 | 站点用户长期记忆
-- 前置：V1 site / site_user，V16 site_ai_conversation
-- 耐久事实由 Java 持有；Python 只抽取，不落库
-- 删除会话时保留记忆，来源会话外键置空
-- =============================================================================

CREATE TABLE site_user_memory (
    id                      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    site_id                 BIGINT NOT NULL,
    user_id                 BIGINT NOT NULL,
    content                 VARCHAR(500) NOT NULL,
    source_conversation_id  BIGINT,
    created_at              TIMESTAMPTZ NOT NULL DEFAULT now(),
    created_by              BIGINT,
    updated_at              TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_by              BIGINT,
    deleted                 BOOLEAN NOT NULL DEFAULT FALSE,
    deleted_at              TIMESTAMPTZ,
    version                 INTEGER NOT NULL DEFAULT 0,
    CONSTRAINT fk_site_user_memory_site
        FOREIGN KEY (site_id) REFERENCES site (id) ON DELETE RESTRICT,
    CONSTRAINT fk_site_user_memory_user
        FOREIGN KEY (user_id) REFERENCES site_user (id) ON DELETE RESTRICT,
    CONSTRAINT fk_site_user_memory_conversation
        FOREIGN KEY (source_conversation_id) REFERENCES site_ai_conversation (id) ON DELETE SET NULL
);

COMMENT ON TABLE site_user_memory IS '站点用户长期记忆；每 (site, user) 由应用层保留最近 50 条';
COMMENT ON COLUMN site_user_memory.content IS '一条独立的耐久事实，最长 500 字';
COMMENT ON COLUMN site_user_memory.source_conversation_id IS '抽取来源会话；会话硬删后置空';

CREATE TRIGGER tr_site_user_memory_touch_updated_at
    BEFORE UPDATE ON site_user_memory
    FOR EACH ROW EXECUTE PROCEDURE fn_touch_updated_at();

CREATE INDEX idx_site_user_memory_site_user_created
    ON site_user_memory (site_id, user_id, created_at DESC) WHERE deleted = FALSE;
