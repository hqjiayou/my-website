-- =============================================================================
-- website-services | Flyway V14 | site_reservation（站点预约工单）
-- 前置：V1 site
-- 跨全部 site type；无冲突引擎/时区列；status 闭集 NEW|CONFIRMED|DONE|CANCELLED
-- =============================================================================

CREATE TABLE site_reservation (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    site_id             BIGINT NOT NULL,
    customer_name       VARCHAR(128) NOT NULL,
    phone               VARCHAR(32) NOT NULL,
    service_type        VARCHAR(128) NOT NULL,
    reserved_at         TIMESTAMPTZ NOT NULL,
    status              VARCHAR(32) NOT NULL,
    note                TEXT,
    created_at          TIMESTAMPTZ NOT NULL DEFAULT now(),
    created_by          BIGINT,
    updated_at          TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_by          BIGINT,
    deleted             BOOLEAN NOT NULL DEFAULT FALSE,
    deleted_at          TIMESTAMPTZ,
    version             INTEGER NOT NULL DEFAULT 0,
    CONSTRAINT fk_site_reservation_site
        FOREIGN KEY (site_id) REFERENCES site (id) ON DELETE RESTRICT,
    CONSTRAINT ck_site_reservation_status CHECK (
        status IN ('NEW', 'CONFIRMED', 'DONE', 'CANCELLED')
    )
);

COMMENT ON TABLE site_reservation IS '站点预约工单；跨 site type；非行业预订引擎';
COMMENT ON COLUMN site_reservation.phone IS '联系电话（PII）；禁止日志打全量';
COMMENT ON COLUMN site_reservation.service_type IS '服务类型自由文本；无服务目录';
COMMENT ON COLUMN site_reservation.reserved_at IS '预约时间（UTC TIMESTAMPTZ）';
COMMENT ON COLUMN site_reservation.status IS 'NEW|CONFIRMED|DONE|CANCELLED';
COMMENT ON COLUMN site_reservation.note IS '可选备注';

CREATE TRIGGER tr_site_reservation_touch_updated_at
    BEFORE UPDATE ON site_reservation
    FOR EACH ROW EXECUTE PROCEDURE fn_touch_updated_at();

CREATE INDEX idx_site_reservation_site_id_active
    ON site_reservation (site_id) WHERE deleted = FALSE;

CREATE INDEX idx_site_reservation_site_status_active
    ON site_reservation (site_id, status) WHERE deleted = FALSE;

CREATE INDEX idx_site_reservation_site_reserved_at_active
    ON site_reservation (site_id, reserved_at) WHERE deleted = FALSE;
