-- =============================================================================
-- website-services | Flyway V57 | 配置预设（Issue #211 UoW-8）
-- agent_ai_prompt_profile 与 agent 1:1、不可共享；本迁移把 Prompt 配置升为
-- 命名预设实体 agent_ai_config_preset，agent 改以 config_preset_id 引用，
-- 多个 agent 可共享同一预设。default_skill_ids 先建列（有序 JSON 数组文本），
-- 正式对话的默认集组装在 UoW-9 接入。
-- 存量平移：每个未删 profile 行生成一条预设并回填该 agent 的引用；
-- 无 profile 的 agent 保持 NULL（解析回退为无配置，与现行逐字一致）。
-- 旧表 agent_ai_prompt_profile 数据不动，退役另行。
-- =============================================================================

CREATE TABLE agent_ai_config_preset (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name                VARCHAR(255) NOT NULL,
    system_prompt       TEXT,
    temperature         NUMERIC(3, 2),
    default_skill_ids   TEXT,
    created_at          TIMESTAMPTZ NOT NULL DEFAULT now(),
    created_by          BIGINT,
    updated_at          TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_by          BIGINT,
    deleted             BOOLEAN NOT NULL DEFAULT FALSE,
    deleted_at          TIMESTAMPTZ,
    version             INTEGER NOT NULL DEFAULT 0,
    CONSTRAINT ck_agent_ai_config_preset_temperature CHECK (
        temperature IS NULL OR (temperature >= 0 AND temperature <= 2)
    )
);

COMMENT ON TABLE agent_ai_config_preset IS 'AI 配置预设（#211）：命名 Prompt＋默认 skill 集，多 agent 共享引用';
COMMENT ON COLUMN agent_ai_config_preset.name IS '预设名称（管理面展示，可改）';
COMMENT ON COLUMN agent_ai_config_preset.system_prompt IS '站点 system prompt；NULL 用运行时默认';
COMMENT ON COLUMN agent_ai_config_preset.temperature IS '0–2；NULL 用 Provider 默认';
COMMENT ON COLUMN agent_ai_config_preset.default_skill_ids IS '默认 skill id 的 JSON 数组文本（有序）；NULL/空＝无预设默认集，正式对话回退平台默认';

CREATE TRIGGER tr_agent_ai_config_preset_touch_updated_at
    BEFORE UPDATE ON agent_ai_config_preset
    FOR EACH ROW EXECUTE PROCEDURE fn_touch_updated_at();

ALTER TABLE agent
    ADD COLUMN config_preset_id BIGINT,
    ADD CONSTRAINT fk_agent_config_preset
        FOREIGN KEY (config_preset_id) REFERENCES agent_ai_config_preset (id) ON DELETE RESTRICT;

COMMENT ON COLUMN agent.config_preset_id IS '引用的配置预设（#211）；NULL＝无预设，解析回退与旧无 profile 一致';

-- 存量平移：逐行生成预设并回填引用（名称：取得到 agent 名用「<agent名> 的配置预设」，
-- 否则「配置预设-<agentId>」；审计列随源行带过来，保持迁移前后可追溯）。
DO $$
DECLARE
    r RECORD;
    new_preset_id BIGINT;
BEGIN
    FOR r IN
        SELECT p.agent_id,
               p.system_prompt,
               p.temperature,
               p.created_at,
               p.created_by,
               p.updated_at,
               p.updated_by,
               a.agent_name
          FROM agent_ai_prompt_profile p
          JOIN agent a ON a.id = p.agent_id
         WHERE p.deleted = FALSE
    LOOP
        INSERT INTO agent_ai_config_preset (
            name, system_prompt, temperature, default_skill_ids,
            created_at, created_by, updated_at, updated_by)
        VALUES (
            CASE
                WHEN r.agent_name IS NOT NULL AND btrim(r.agent_name) <> ''
                    THEN r.agent_name || ' 的配置预设'
                ELSE '配置预设-' || r.agent_id
            END,
            r.system_prompt, r.temperature, NULL,
            r.created_at, r.created_by, r.updated_at, r.updated_by)
        RETURNING id INTO new_preset_id;

        UPDATE agent SET config_preset_id = new_preset_id WHERE id = r.agent_id;
    END LOOP;
END $$;
