-- =============================================================================
-- website-services | Flyway V45 | AI 用量记账一表制（Issue #140）
-- 一表三吃：Portal 聊天（PORTAL）、后台试聊（ADMIN_PREVIEW）、对外 /v1 网关
-- （GATEWAY_V1）在同一张表记 token 级用量，供后台按日／agent／模型聚合。
-- 不记请求/回应正文。tokens 拿不到时记 NULL，禁止用 0 冒充。
-- entry_id 归属语义：ADMIN_PREVIEW 与 GATEWAY_V1 为实际应答入口（精确）；
-- PORTAL 因备援在 Python 执行层内部切换，Java 按 runMeta 的实际模型名与
-- 本轮链比对做 best-effort 判定（细节见 AgentAiServiceImpl 的记账注释）。
-- =============================================================================

CREATE TABLE agent_ai_usage (
    id                    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    agent_id              BIGINT,
    entry_id              BIGINT,
    alias                 VARCHAR(64),
    mode                  VARCHAR(8),
    source                VARCHAR(16) NOT NULL,
    prompt_tokens         BIGINT,
    completion_tokens     BIGINT,
    latency_ms            BIGINT,
    status                VARCHAR(24) NOT NULL,
    gateway_access_key_id BIGINT,
    created_at            TIMESTAMPTZ NOT NULL DEFAULT now(),
    created_by            BIGINT,
    updated_at            TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_by            BIGINT,
    deleted               BOOLEAN NOT NULL DEFAULT FALSE,
    deleted_at            TIMESTAMPTZ,
    version               INTEGER NOT NULL DEFAULT 0,
    CONSTRAINT ck_agent_ai_usage_source CHECK (source IN ('PORTAL', 'ADMIN_PREVIEW', 'GATEWAY_V1')),
    CONSTRAINT ck_agent_ai_usage_status CHECK (status IN ('SUCCESS', 'UPSTREAM_ERROR')),
    CONSTRAINT ck_agent_ai_usage_mode CHECK (mode IS NULL OR mode IN ('KEY', 'CLI'))
);

COMMENT ON TABLE agent_ai_usage IS 'AI 用量记账（#140）：每条用户请求一行，不记请求/回应正文';
COMMENT ON COLUMN agent_ai_usage.agent_id IS '站点 id；全站入口或网关全局入口时为空';
COMMENT ON COLUMN agent_ai_usage.entry_id IS '模型入口 id；归属语义见脚本头注释';
COMMENT ON COLUMN agent_ai_usage.alias IS '对外模型名；仅 GATEWAY_V1 有';
COMMENT ON COLUMN agent_ai_usage.mode IS '本轮模式：KEY／CLI';
COMMENT ON COLUMN agent_ai_usage.source IS '来源：PORTAL／ADMIN_PREVIEW／GATEWAY_V1';
COMMENT ON COLUMN agent_ai_usage.prompt_tokens IS '输入 tokens；拿不到记 NULL，不记 0';
COMMENT ON COLUMN agent_ai_usage.completion_tokens IS '输出 tokens；拿不到记 NULL，不记 0';
COMMENT ON COLUMN agent_ai_usage.latency_ms IS '本轮端到端耗时（毫秒，Java 侧测量）';
COMMENT ON COLUMN agent_ai_usage.status IS 'SUCCESS＝成功应答；UPSTREAM_ERROR＝上游最终失败（本期仅 GATEWAY_V1 使用）';
COMMENT ON COLUMN agent_ai_usage.gateway_access_key_id IS '网关访问 Key id；仅 GATEWAY_V1 有';

CREATE TRIGGER tr_agent_ai_usage_touch_updated_at
    BEFORE UPDATE ON agent_ai_usage
    FOR EACH ROW EXECUTE PROCEDURE fn_touch_updated_at();

CREATE INDEX idx_agent_ai_usage_created_at ON agent_ai_usage (created_at DESC);
CREATE INDEX idx_agent_ai_usage_agent_created ON agent_ai_usage (agent_id, created_at DESC);
CREATE INDEX idx_agent_ai_usage_source_created ON agent_ai_usage (source, created_at DESC);
