-- website-services | Flyway V63 | 对话链预设（Issue #210 UoW-7，解耦 Phase 2）
-- 新表 agent_ai_chain_preset：命名的有序入口集合（用途 v1 只有 CHAT＝对话）；
-- agent 改以 chain_preset_id 引用其对话链预设（落点对齐 #211 的
-- config_preset_id：agent 表 FK 列、ON DELETE RESTRICT、软删拦截在服务层）。
-- 组链自本版起吃预设快照：按预设的有序 entry ids 取入口、过滤停用后交
-- ModelChainResolver 既有规则（mode 过滤、默认/备援序、坏主用整链空）；
-- UoW-6 的「来源分层」过渡组链整体退役，source_agent_id 只留来源标注。
--
-- 存量自动生成口径（主控定死）：每个未删 agent 的预设＝其「平台化之前」的
-- 有效链，按 UoW-6 等价测试的旧语义从来源标注重构——source_agent_id＝本
-- agent 的入口在前、source_agent_id IS NULL 的平台入口在后，两段内各按
-- 「默认在前、id 升序」；严禁用 UoW-6 改造后的单一平台链当生成源（会把各
-- agent 的旧链抹平）。有序 id 列表完全相同的 agent 共用同一条预设（去重）；
-- 无专属入口的 agent 得到纯平台链预设、同样去重共用。成员口径含停用入口：
-- 成员资格与启用状态无关，停用入口只是组链时被过滤，日后重新启用自动回链。
-- 命名：含专属入口的预设为「迁移预设·<agent 名>」（名为空时「迁移预设·Agent-<id>」），
-- 纯平台链预设为「迁移预设·平台链」。
-- =============================================================================

CREATE TABLE agent_ai_chain_preset (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        VARCHAR(255) NOT NULL,
    purpose     VARCHAR(32) NOT NULL DEFAULT 'CHAT',
    entry_ids   TEXT,
    created_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
    created_by  BIGINT,
    updated_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_by  BIGINT,
    deleted     BOOLEAN NOT NULL DEFAULT FALSE,
    deleted_at  TIMESTAMPTZ,
    version     INTEGER NOT NULL DEFAULT 0,
    CONSTRAINT ck_agent_ai_chain_preset_purpose CHECK (purpose IN ('CHAT'))
);

COMMENT ON TABLE agent_ai_chain_preset IS '对话链预设（#210 UoW-7）：命名的有序模型入口集合，多 agent 共享引用';
COMMENT ON COLUMN agent_ai_chain_preset.name IS '预设名称（管理面展示，可改）';
COMMENT ON COLUMN agent_ai_chain_preset.purpose IS '用途：v1 只有 CHAT（对话链）';
COMMENT ON COLUMN agent_ai_chain_preset.entry_ids IS '成员入口 id 的 JSON 数组文本（有序）；成员资格与启用状态无关，组链时只取启用入口';

CREATE TRIGGER tr_agent_ai_chain_preset_touch_updated_at
    BEFORE UPDATE ON agent_ai_chain_preset
    FOR EACH ROW EXECUTE PROCEDURE fn_touch_updated_at();

ALTER TABLE agent
    ADD COLUMN chain_preset_id BIGINT,
    ADD CONSTRAINT fk_agent_chain_preset
        FOREIGN KEY (chain_preset_id) REFERENCES agent_ai_chain_preset (id) ON DELETE RESTRICT;

COMMENT ON COLUMN agent.chain_preset_id IS '引用的对话链预设（#210 UoW-7）；NULL＝未引用预设，对话链为空（诚实无模型）';

-- 存量生成：逐 agent 按旧语义重构有序 id 列表，同列表复用同一条预设（去重），
-- 最后回填引用。列表文本由同一表达式生成，jsonb 序列化确定，文本相等即同链。
DO $$
DECLARE
    r RECORD;
    platform_ids JSONB;
    own_ids JSONB;
    full_text TEXT;
    existing_id BIGINT;
    preset_name TEXT;
BEGIN
    SELECT COALESCE(jsonb_agg(e.id ORDER BY e.is_default DESC, e.id), '[]'::jsonb)
      INTO platform_ids
      FROM agent_model_entry e
     WHERE e.source_agent_id IS NULL
       AND e.deleted = FALSE;

    FOR r IN
        SELECT a.id, a.agent_name
          FROM agent a
         WHERE a.deleted = FALSE
         ORDER BY a.id
    LOOP
        SELECT COALESCE(jsonb_agg(e.id ORDER BY e.is_default DESC, e.id), '[]'::jsonb)
          INTO own_ids
          FROM agent_model_entry e
         WHERE e.source_agent_id = r.id
           AND e.deleted = FALSE;

        full_text := (own_ids || platform_ids)::text;

        SELECT p.id
          INTO existing_id
          FROM agent_ai_chain_preset p
         WHERE p.entry_ids = full_text
         LIMIT 1;

        IF existing_id IS NULL THEN
            IF jsonb_array_length(own_ids) > 0 THEN
                preset_name := '迁移预设·' || CASE
                    WHEN r.agent_name IS NOT NULL AND btrim(r.agent_name) <> ''
                        THEN r.agent_name
                    ELSE 'Agent-' || r.id
                END;
            ELSE
                preset_name := '迁移预设·平台链';
            END IF;

            INSERT INTO agent_ai_chain_preset (name, purpose, entry_ids)
            VALUES (preset_name, 'CHAT', full_text)
            RETURNING id INTO existing_id;
        END IF;

        UPDATE agent SET chain_preset_id = existing_id WHERE id = r.id;
    END LOOP;
END $$;
