CREATE TABLE site_ai_knowledge_document (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    site_id             BIGINT NOT NULL,
    title               VARCHAR(255) NOT NULL,
    content             TEXT NOT NULL,
    status              VARCHAR(16) NOT NULL,
    created_at          TIMESTAMPTZ NOT NULL DEFAULT now(),
    created_by          BIGINT,
    updated_at          TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_by          BIGINT,
    deleted             BOOLEAN NOT NULL DEFAULT FALSE,
    deleted_at          TIMESTAMPTZ,
    version             INTEGER NOT NULL DEFAULT 0,
    CONSTRAINT fk_site_ai_knowledge_document_site
        FOREIGN KEY (site_id) REFERENCES site (id) ON DELETE RESTRICT,
    CONSTRAINT ck_site_ai_knowledge_document_status CHECK (
        status IN ('ACTIVE', 'DISABLED')
    )
);

COMMENT ON TABLE site_ai_knowledge_document IS 'AI 知识库文档（SoT）；派生索引在 agent_retrieval，允许滞后';
COMMENT ON COLUMN site_ai_knowledge_document.status IS 'ACTIVE 参与检索派生；DISABLED 从派生索引移除';

CREATE TRIGGER tr_site_ai_knowledge_document_touch_updated_at
    BEFORE UPDATE ON site_ai_knowledge_document
    FOR EACH ROW EXECUTE PROCEDURE fn_touch_updated_at();

CREATE INDEX idx_site_ai_knowledge_document_site_active
    ON site_ai_knowledge_document (site_id) WHERE deleted = FALSE;

INSERT INTO admin_permission (
    permission_code, permission_name, resource_type, resource_key, status,
    parent_id, sort_order, route_path, icon, deleted, version)
SELECT v.code, v.name, 'ACTION', v.rkey, 'ACTIVE',
       NULL, 0, NULL, NULL, FALSE, 0
FROM (VALUES
    ('admin:ai-kb:list', '列出 AI 知识库文档', 'ai-kb:list'),
    ('admin:ai-kb:create', '创建 AI 知识库文档', 'ai-kb:create'),
    ('admin:ai-kb:update', '更新 AI 知识库文档', 'ai-kb:update'),
    ('admin:ai-kb:delete', '删除 AI 知识库文档', 'ai-kb:delete')
) AS v(code, name, rkey)
WHERE NOT EXISTS (
    SELECT 1 FROM admin_permission p
    WHERE p.permission_code = v.code AND p.deleted = FALSE
);

INSERT INTO admin_role_permission (admin_role_id, admin_permission_id, deleted, version)
SELECT r.id, p.id, FALSE, 0
FROM admin_role r
CROSS JOIN admin_permission p
WHERE r.role_code = 'admin'
  AND r.deleted = FALSE
  AND p.deleted = FALSE
  AND p.status = 'ACTIVE'
  AND p.permission_code LIKE 'admin:ai-kb:%'
  AND NOT EXISTS (
      SELECT 1 FROM admin_role_permission rp
      WHERE rp.admin_role_id = r.id
        AND rp.admin_permission_id = p.id
        AND rp.deleted = FALSE
  );
