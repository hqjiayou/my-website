-- ---------------------------------------------------------------------------
-- §1 site_template：平台级系统预置模板目录（非站点实例配置）
-- ---------------------------------------------------------------------------
CREATE TABLE site_template (
    id                      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code                    VARCHAR(64) NOT NULL,
    name                    VARCHAR(255) NOT NULL,
    site_type               VARCHAR(32) NOT NULL,
    status                  VARCHAR(32) NOT NULL DEFAULT 'DRAFT',
    description             TEXT,
    preview_image_url       VARCHAR(512),
    -- 目录卡片提示色 only；Appearance 真相源属 Phase 5，本轮不写入站点外观
    default_primary_color   VARCHAR(32),
    sort_order              INTEGER NOT NULL DEFAULT 0,
    created_at              TIMESTAMPTZ NOT NULL DEFAULT now(),
    created_by              BIGINT,
    updated_at              TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_by              BIGINT,
    deleted                 BOOLEAN NOT NULL DEFAULT FALSE,
    deleted_at              TIMESTAMPTZ,
    version                 INTEGER NOT NULL DEFAULT 0
);

COMMENT ON TABLE site_template IS '平台级系统预置站点模板目录；无 site_id；内容字段本轮仅 seed，无运营 CRUD API';
COMMENT ON COLUMN site_template.code IS '模板编码，软删除外唯一；版本语义落在稳定 code（如 *-v1）';
COMMENT ON COLUMN site_template.site_type IS '对齐 site.site_type 闭集：CAR_REPAIR/USED_CAR/CAKE/SALON/CLINIC/GYOSEISHOSHI';
COMMENT ON COLUMN site_template.status IS 'ENABLED / DRAFT / DISABLED';
COMMENT ON COLUMN site_template.default_primary_color IS '目录展示用默认主色提示；非 Appearance 持久化真相源';

CREATE TRIGGER tr_site_template_touch_updated_at
    BEFORE UPDATE ON site_template
    FOR EACH ROW EXECUTE PROCEDURE fn_touch_updated_at();

CREATE UNIQUE INDEX uq_site_template_code_active
    ON site_template (code) WHERE deleted = FALSE;

CREATE INDEX idx_site_template_site_type_active
    ON site_template (site_type) WHERE deleted = FALSE;

CREATE INDEX idx_site_template_status_active
    ON site_template (status) WHERE deleted = FALSE;

