-- =============================================================================
-- website-services | Flyway V36 | 对外 API 网关：模型入口 alias ＋ 网关访问 Key（UoW-1a 后端）
-- alias：对外模型名，外部客户端以此选模型，不暴露内部 model_spec/agentId。
-- gateway_access_key：网关侧访问凭证；key_hash 为明文 SHA-256 十六进制，明文只在签发响应中出现一次。
-- =============================================================================

ALTER TABLE agent_model_entry
    ADD COLUMN alias VARCHAR(64);

COMMENT ON COLUMN agent_model_entry.alias IS '对外模型名，外部客户端以此选模型';

CREATE UNIQUE INDEX uq_agent_model_entry_alias
    ON agent_model_entry (alias) WHERE alias IS NOT NULL AND deleted = FALSE;

CREATE TABLE gateway_access_key (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name                VARCHAR(128) NOT NULL,
    key_hash            VARCHAR(64) NOT NULL,
    key_hint            VARCHAR(16) NOT NULL,
    expires_at          TIMESTAMPTZ,
    revoked_at          TIMESTAMPTZ,
    created_at          TIMESTAMPTZ NOT NULL DEFAULT now(),
    created_by          BIGINT,
    updated_at          TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_by          BIGINT,
    deleted             BOOLEAN NOT NULL DEFAULT FALSE,
    deleted_at          TIMESTAMPTZ,
    version             INTEGER NOT NULL DEFAULT 0,
    CONSTRAINT ck_gateway_access_key_name CHECK (length(trim(name)) > 0),
    CONSTRAINT ck_gateway_access_key_key_hash CHECK (length(trim(key_hash)) > 0)
);

COMMENT ON TABLE gateway_access_key IS '对外 API 网关访问凭证；key_hash 不得出现在管理接口响应中，明文只在签发时一次性返回';
COMMENT ON COLUMN gateway_access_key.key_hash IS '明文 key 的 SHA-256 十六进制（小写）';
COMMENT ON COLUMN gateway_access_key.key_hint IS '明文 key 尾 4 位，用于列表展示';
COMMENT ON COLUMN gateway_access_key.revoked_at IS '非空表示已吊销；吊销后不可再用于认证';

CREATE TRIGGER tr_gateway_access_key_touch_updated_at
    BEFORE UPDATE ON gateway_access_key
    FOR EACH ROW EXECUTE PROCEDURE fn_touch_updated_at();

CREATE UNIQUE INDEX uq_gateway_access_key_key_hash ON gateway_access_key (key_hash);
