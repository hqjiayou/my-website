-- 测试 H2 schema：AI 表 + internal API 触达的业务表（无 FK/触发器；生产 DDL 见 Flyway）
CREATE TABLE IF NOT EXISTS site (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    site_code           VARCHAR(64),
    site_name           VARCHAR(255),
    site_type           VARCHAR(32),
    status              VARCHAR(32),
    default_domain      VARCHAR(255),
    description         TEXT,
    template_id         BIGINT,
    created_at          TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT now(),
    created_by          BIGINT,
    updated_at          TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT now(),
    updated_by          BIGINT,
    deleted             BOOLEAN NOT NULL DEFAULT FALSE,
    deleted_at          TIMESTAMP WITH TIME ZONE,
    version             INTEGER NOT NULL DEFAULT 0
);

CREATE TABLE IF NOT EXISTS site_content (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    site_id             BIGINT NOT NULL,
    type                VARCHAR(32) NOT NULL,
    title               VARCHAR(255) NOT NULL,
    body                TEXT,
    status              VARCHAR(32) NOT NULL,
    sort_order          INTEGER NOT NULL DEFAULT 0,
    cover_media_id      BIGINT,
    published_at        TIMESTAMP WITH TIME ZONE,
    created_at          TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT now(),
    created_by          BIGINT,
    updated_at          TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT now(),
    updated_by          BIGINT,
    deleted             BOOLEAN NOT NULL DEFAULT FALSE,
    deleted_at          TIMESTAMP WITH TIME ZONE,
    version             INTEGER NOT NULL DEFAULT 0
);

CREATE TABLE IF NOT EXISTS site_reservation (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    site_id             BIGINT NOT NULL,
    customer_name       VARCHAR(128) NOT NULL,
    phone               VARCHAR(32) NOT NULL,
    service_type        VARCHAR(128) NOT NULL,
    reserved_at         TIMESTAMP WITH TIME ZONE NOT NULL,
    status              VARCHAR(32) NOT NULL,
    note                TEXT,
    idempotency_key     VARCHAR(128),
    created_at          TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT now(),
    created_by          BIGINT,
    updated_at          TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT now(),
    updated_by          BIGINT,
    deleted             BOOLEAN NOT NULL DEFAULT FALSE,
    deleted_at          TIMESTAMP WITH TIME ZONE,
    version             INTEGER NOT NULL DEFAULT 0
);

CREATE TABLE IF NOT EXISTS site_ai_knowledge_document (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    site_id             BIGINT NOT NULL,
    title               VARCHAR(255) NOT NULL,
    content             TEXT NOT NULL,
    status              VARCHAR(16) NOT NULL,
    created_at          TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT now(),
